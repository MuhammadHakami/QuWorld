"""Summaries of ADR-C runs (docs 35 §6/§8, 36): per cache dir and arm, TEST VRMSE mean ± sample SD over seeds, the
anchors (unblended trunk, cached anchor, persistence where audited), and the decisive paired contrasts.

    .venv/bin/python paper/alloc/adrc_summary.py            # -> runs/alloc/adrc_summary.{md,json}
"""
from __future__ import annotations

import collections
import json
import pathlib
import statistics as st

ROOT = pathlib.Path(__file__).resolve().parents[2]
RES, OUT = ROOT / "runs/alloc/adrc_results", ROOT / "runs/alloc"
ARMS = ["none", "cls_only", "static_lin", "adrc_ryd", "adrc_gnn", "adrc_mlp", "frozen_ryd", "adrc_gutz", "rand_ryd"]
CONTRASTS = [("adrc_ryd", "adrc_gnn"), ("adrc_ryd", "adrc_mlp"), ("adrc_ryd", "adrc_gutz"), ("adrc_ryd", "static_lin")]


def persistence(row: str):
    f = ROOT / "runs/persistence" / f"{row.split('__')[0]}_summary.json"
    return json.loads(f.read_text())["persistence_mean"] if f.exists() else None


def load():
    runs = collections.defaultdict(dict)
    for f in sorted(RES.glob("*.json")):
        d = json.loads(f.read_text())
        if "test_shots" in d or "test_noise" in d or d.get("atoms", 30) != 30 or d.get("dyn_tether"):                                   # doc 35 §11 finite-shot evals: reported separately
            continue
        key = (d["row"], d.get("gate", False), d.get("route_sup", False), d.get("qubit_bands") or "")
        runs[key].setdefault(d["arm"], {})[d["seed"]] = d
    return runs


def msd(v):
    return (st.mean(v), st.stdev(v) if len(v) > 1 else 0.0)


def main():
    runs, rows, md = load(), [], ["| cache | gate | arm | n | TEST VRMSE | rel. gain vs anchor |", "|---|---|---|---|---|---|"]
    for (row, gate, rsup, qb), arms in sorted(runs.items()):
        any_run = next(iter(next(iter(arms.values())).values()))
        rec = {"row": row, "gate": gate, "route_sup": rsup, "qubit_bands": qb, "anchor_test": any_run["trunk_test"], "trunk0_test": any_run.get("trunk0_test"),
               "persistence_test": persistence(row), "arms": {}, "contrasts": {}}
        for arm in ARMS:
            if arm not in arms:
                continue
            seeds = sorted(arms[arm]); t = [arms[arm][s]["test"] for s in seeds]
            m, sd = msd(t)
            rec["arms"][arm] = {"seeds": seeds, "test": t, "mean": m, "sd": sd,
                                "rel_gain": 1 - m / rec["anchor_test"],
                                "bands": arms[arm][seeds[0]].get("bands_test")}
            md.append(f"| {row}{' (route-sup)' if rsup else ''}{f' (qubits in b{qb})' if qb else ''} | {'yes' if gate else 'no'} | {arm} | {len(t)} | {m:.5f} ± {sd:.5f} | {100 * (1 - m / rec['anchor_test']):+.2f} % |")
        for a, b in CONTRASTS:
            if a in arms and b in arms:
                common = sorted(set(arms[a]) & set(arms[b]))
                diff = [arms[b][s]["test"] - arms[a][s]["test"] for s in common]   # > 0: a (register) better
                rec["contrasts"][f"{a}_vs_{b}"] = {"seeds": common, "b_minus_a": diff,
                                                   "a_better": sum(x > 0 for x in diff), "n": len(diff)}
        rows.append(rec)
    (OUT / "adrc_summary.json").write_text(json.dumps(rows, indent=1))
    lines = ["# ADR-C summary (auto-generated by paper/alloc/adrc_summary.py)", "",
             "Anchor = the cached trunk prediction the co-processor corrects: the released or fine-tuned trunk, or the TRAIN-fitted band blend for `__gate_*` caches.",
             "`none` with gate = the per-window gate alone. `trunk0` = unblended trunk. Persistence from runs/persistence.", ""]
    for r in rows:
        lines.append(f"- {r['row']} (gate {r['gate']}{', route-sup' if r['route_sup'] else ''}): anchor {r['anchor_test']:.5f}"
                     + (f", trunk0 {r['trunk0_test']:.5f}" if r["trunk0_test"] else "")
                     + (f", persistence {r['persistence_test']:.4f}" if r["persistence_test"] else "")
                     + "; " + ", ".join(f"{k}: {v['a_better']}/{v['n']}" for k, v in r["contrasts"].items()))
    (OUT / "adrc_summary.md").write_text("\n".join(lines + [""] + md) + "\n")
    print("\n".join(lines + [""] + md))


if __name__ == "__main__":
    main()
