"""Table 1, top block (published SoTA -> classical -> +MLP -> +30/+50/+100 qubits) and the doc 35 §22 geometry control,
printed from the per-seed result files (test split, mean over the registered seeds 1-3; the §26 replication seeds 4-8
are reported separately). --latex also writes the block's rows to paper/manuscript/iclr2027/tab_routed_rows.tex, which
the paper \\inputs, so the table follows the result files (best value per row in bold; vs columns at 30 qubits).

    python paper/alloc/table1_routed.py [--latex]
"""
import glob
import sys
import json
import pathlib
import statistics as st

ROOT = pathlib.Path(__file__).resolve().parents[2]
R = ROOT / "runs/alloc/adrc_results"
S22 = ROOT / "runs/alloc/adrc_results_s22"
S32 = ROOT / "runs/alloc/adrc_results_s32"
# doc 35 §32: all 15 full-TEST cells exist (locked-recipe retraining, every test window), so Table 1's RB row reads them;
# the stratified-sample values stay in runs/alloc/adrc_results and are quoted in the appendix.
TABLE_SRC = {"rayleigh_benard": (S32, "rayleigh_benard__gatestfull_vanilla_s1337")}
# best published one-step TEST VRMSE: PDE-FM (arXiv:2511.21861, Table 3) on shear/RB; Flowers (arXiv:2603.04430,
# Table 1, 4->1 unconditioned) on TRL2D; EddyFormer (NeurIPS 2025, Table 3) on MHD. Reference only: bold = best of ours.
PUB = {"shear_flow": 0.0345, "rayleigh_benard": 0.0415, "turbulent_radiative_layer_2D": 0.1930, "MHD_64": 0.1160}
# our best classical lift per row (Appendix app:sota; e = ensemble): shear = this table's +100 qubits cell (3 seeds); RB = gated
# metric-aligned 3-backbone ensemble; TRL2D = gated fine-tuned 3-backbone ensemble; MHD = Flowers + gated CNextU-net blend
BEST = {"shear_flow": (0.0198, ""), "rayleigh_benard": (0.0403, "e"), "turbulent_radiative_layer_2D": (0.1909, "e"), "MHD_64": (0.1154, "e")}


def best_cell(name):
    v, tag = BEST[name]; t = f"{v:.4f}" + (f"$^{tag}$" if tag else "")
    return f"\\textbf{{{v:.4f}}}" + (f"$^{tag}$" if tag else "") if v < PUB[name] else t
NAMES = {"shear_flow": "shear flow", "rayleigh_benard": "convection (RB)", "turbulent_radiative_layer_2D": "turbulence (TRL2D)",
         "MHD_64": "MHD (MHD\\_64)"}
TEX = ROOT / "paper/manuscript/iclr2027/tab_routed_rows.tex"
SEEDS = "s[123]"
ROWS = (("shear_flow", "shear_flow__gate_vanilla_s1337"), ("rayleigh_benard", "rayleigh_benard__gatest_vanilla_s1337"),
        ("turbulent_radiative_layer_2D", "turbulent_radiative_layer_2D__gate_vanilla_s1337"),
        ("MHD_64", "MHD_64__gate_vanilla_s1337"))


def mean_test(pattern: str):
    fs = sorted(glob.glob(str(pattern)))
    return (st.mean(json.loads(pathlib.Path(f).read_text())["test"] for f in fs), len(fs)) if fs else (None, 0)


def cells(key, d=R):
    return (mean_test(d / f"{key}_adrc_mlp_gate_rs_dyn_{SEEDS}.json"), mean_test(d / f"{key}_adrc_ryd_gate_rs_dyn_{SEEDS}.json"),
            mean_test(d / f"{key}_adrc_ryd_gate_rs_k50_dyn_{SEEDS}.json"), mean_test(d / f"{key}_adrc_ryd_gate_rs_k100_dyn_{SEEDS}.json"))


def pct(ref, new):
    if ref is None or new is None:
        return "---"
    v = 100 * (ref - new) / ref
    return "$0.0\\%$" if abs(v) < 0.05 else f"${v:+.1f}\\%$"


def latex_rows() -> str:
    """Rows of Table 1's routed block: published, classical, +MLP, +30, +50, +100 qubits, vs MLP, vs classical."""
    out = []
    for name, key in ROWS:
        d, key = TABLE_SRC.get(name, (R, key))
        c = mean_test(d / f"{key}_cls_only_gate_s*.json")[0]
        m, q, q50, q100 = (v[0] if v[1] >= 3 else None for v in cells(key, d))        # registered cells: all 3 seeds
        vals = [PUB[name], c, m, q, q50, q100]
        best = min(round(v, 4) for v in vals[1:] if v is not None)          # our models only (published = reference)
        cell = lambda v: "---" if v is None else (f"\\textbf{{{v:.4f}}}" if round(v, 4) == best else f"{v:.4f}")
        out.append(f"{NAMES[name]} & {PUB[name]:.4f} & {best_cell(name)} & " + " & ".join(cell(v) for v in vals[1:]) + f" & {pct(m, q)} & {pct(c, q)} \\\\")
    return "% generated by paper/alloc/table1_routed.py --latex (do not edit)\n" + "\n".join(out) + "\n"


def fmt(v):
    return "   ---  " if v[0] is None else f"{v[0]:.4f}({v[1]})"


def main() -> None:
    print("Table 1, routed co-processor (test VRMSE, mean over seeds; (n) = seeds)")
    print(f"{'row':30s} {'published':>9s} {'classical':>10s} {'+MLP':>10s} {'+30 qubits':>10s} {'+50 qubits':>10s} {'+100':>10s} {'gain30':>7s}")
    for name, key in ROWS:
        d, key = TABLE_SRC.get(name, (R, key))                                 # same source as the LaTeX rows (§32)
        c = mean_test(d / f"{key}_cls_only_gate_s*.json")
        m, q, q50, q100 = cells(key, d)
        g = f"{100 * (c[0] - q[0]) / c[0]:+.1f}%" if c[0] and q[0] else "---"
        print(f"{name:30s} {PUB[name]:9.4f} {fmt(c):>10s} {fmt(m):>10s} {fmt(q):>10s} {fmt(q50):>10s} {fmt(q100):>10s} {g:>7s}")
    if "--latex" in sys.argv:
        TEX.write_text(latex_rows()); print("wrote", TEX)
    print("\ndoc 35 §22 control, 30 atoms, same routing (test VRMSE)")
    for name, key in ROWS[:2]:
        a = mean_test(R / f"{key}_adrc_ryd_gate_rs_dyn_{SEEDS}.json")
        b = mean_test(S22 / "frozen" / f"{key}_frozen_ryd*_s[0-9].json")
        c = mean_test(S22 / "3d" / f"{key}_adrc_ryd*_s[0-9].json")
        m = mean_test(R / f"{key}_adrc_mlp_gate_rs_dyn_{SEEDS}.json")
        print(f"{name:18s} per-input 2-D {fmt(a)}  fixed grid {fmt(b)}  3-D {fmt(c)}  MLP {fmt(m)}")


if __name__ == "__main__":
    main()
