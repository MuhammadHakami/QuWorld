"""Doc 35 §28 M1 + addendum: apply the registered VALID rules to the screen and the exact_eps control.

  (i)   the emulated array reaches the ceiling: rydberg gap within 0.02 pp of exact (or below it), both seeds;
  (ii)  combinatorial selection beats best1 at equal rounds (>= 1% relative lower gap);
  (add) randomised-selection control: if exact_eps1 or exact_eps2 reaches rydberg's gap (within 0.01 pp) on >= 3 of 4
        variants, the rydberg edge is attributed to randomised selection, not to the blockade dynamics;
  (add) paired one-sided Wilcoxon of exact - rydberg per-instance cost (alternative: rydberg lower), Holm across the
        4 variants x 2 seeds; "systematic" needs all four variants in the same direction with p < 0.05 after Holm.
Both starts (policy, nearest neighbour) are reported; the addendum was written on the policy start.

    .venv/bin/python paper/qmethods/m1_summary.py   ->  runs/qmethods/m1/summary.md
"""
from __future__ import annotations

import json
import pathlib

import numpy as np
from scipy.stats import wilcoxon

ROOT = pathlib.Path(__file__).resolve().parents[2]
D = ROOT / "runs/qmethods/m1"
VARIANTS = ("mdcvrp", "mdovrp", "mdvrpl", "mdovrpl")
SEEDS = (1, 2)


def load(seed: int, tag: str = "") -> dict:
    return json.loads((D / f"m1_val_eal_md_vanilla_s1_s{seed}{tag}.json").read_text())["variants"]


def holm(ps: list[float]) -> list[float]:
    order, out, m = np.argsort(ps), [0.0] * len(ps), len(ps)
    run = 0.0
    for r, i in enumerate(order):
        run = max(run, min(1.0, (m - r) * ps[i])); out[i] = run
    return out


def start_block(start: str, scr: dict, ctl: dict) -> list[str]:
    g = lambda s, v, sel, src=scr: src[s][v][f"{start}+{sel}"]["gap"]
    L = [f"### start = {start}", "", "| variant | seed | best1 | greedy | anneal | exact | rydberg | eps1 | eps2 | ryd-exact (pp) |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    ceil_ok, beats, eps_hits, cells = True, True, {v: True for v in VARIANTS}, []
    for v in VARIANTS:
        for s in SEEDS:
            r, e = g(s, v, "rydberg"), g(s, v, "exact")
            e1, e2 = g(s, v, "exact_eps1", ctl), g(s, v, "exact_eps2", ctl)
            ceil_ok &= r - e <= 0.02
            beats &= min(g(s, v, x) for x in ("greedy", "anneal", "rydberg", "exact")) <= 0.99 * g(s, v, "best1")
            eps_hits[v] &= min(e1, e2) - r <= 0.01
            ce, cr = np.array(scr[s][v][f"{start}+exact"]["cost"]), np.array(scr[s][v][f"{start}+rydberg"]["cost"])
            d = ce - cr
            p = float(wilcoxon(d, alternative="greater").pvalue) if np.any(d != 0) else 1.0
            cells.append((v, s, float(d.mean()), p))
            L.append(f"| {v} | {s} | {g(s, v, 'best1'):.3f} | {g(s, v, 'greedy'):.3f} | {g(s, v, 'anneal'):.3f} | {e:.3f} | "
                     f"{r:.3f} | {e1:.3f} | {e2:.3f} | {r - e:+.3f} |")
    padj = holm([c[3] for c in cells])
    L += ["", "| variant | seed | mean(exact - rydberg) cost | one-sided p | Holm p |", "|---|---|---|---|---|"]
    L += [f"| {v} | {s} | {m:+.5f} | {p:.4f} | {q:.4f} |" for (v, s, m, p), q in zip(cells, padj)]
    same_dir = all(m > 0 for _, _, m, _ in cells) and all(q < 0.05 for q in padj)
    n_eps = sum(eps_hits.values())
    L += ["", f"- (i) array reaches the ceiling (rydberg <= exact + 0.02 pp, every variant and seed): {'PASS' if ceil_ok else 'FAIL'}",
          f"- (ii) combinatorial selection beats best1 by >= 1% relative, every variant and seed: {'PASS' if beats else 'FAIL'}",
          f"- control: exact_eps reaches rydberg (within 0.01 pp, both seeds) on {n_eps}/4 variants -> "
          + ("edge attributed to randomised selection" if n_eps >= 3 else "not attributed to randomised selection"),
          f"- systematic rydberg < exact (all 8 cells positive, Holm p < 0.05): {'yes' if same_dir else 'no'}", ""]
    return L


def main() -> None:
    scr = {s: load(s) for s in SEEDS}
    ctl = {s: load(s, "_ctrl") for s in SEEDS}
    L = ["# §28 M1 screen + exact_eps control (VALID, 128 instances per variant; generated by paper/qmethods/m1_summary.py)", ""]
    for start in ("policy", "nn"):
        L += start_block(start, scr, ctl)
    text = "\n".join(L) + "\n"
    (D / "summary.md").write_text(text); print(text)


if __name__ == "__main__":
    main()
